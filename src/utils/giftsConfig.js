/** Legacy / shorthand slugs → real catalog IDs */
export const GIFT_ID_ALIASES = {
  crown: "little_crown",
  littlecrown: "little_crown",
  gamepad: "puppy_gamepad",
  puppygamepad: "puppy_gamepad",
  universe: "tiktok_universe",
  tiktokuniverse: "tiktok_universe",
};

/** Gift IDs used by default paid power-up rules (ship these PNGs). */
export const ACTIVE_RULE_GIFT_IDS = [
  "rose",
  "finger_heart",
  "doughnut",
  "tiktok",
  "gg",
  "little_crown",
  "puppy_gamepad",
  "lion",
  "perfume",
  "tiktok_universe",
];

/** PNGs that still exist under public/assets/GIFTS PNGS after the trim. */
export const LOCAL_GIFT_ICON_IDS = new Set(ACTIVE_RULE_GIFT_IDS);

export function hasLocalGiftIcon(giftId) {
  const id = resolveGiftId(giftId) || giftId;
  return LOCAL_GIFT_ICON_IDS.has(id);
}

export function normalizeGiftKey(value) {
  return String(value || "").toLowerCase().replace(/[^a-z0-9]/g, "");
}

/** Resolve alias / catalog id without Rose fallback (null if unknown). */
export function resolveGiftId(incomingIdentifier) {
  if (incomingIdentifier == null || incomingIdentifier === "") return null;
  const raw = String(incomingIdentifier).trim();
  const normalized = normalizeGiftKey(raw);

  if (GIFT_ID_ALIASES[normalized]) return GIFT_ID_ALIASES[normalized];
  if (GIFT_ID_ALIASES[raw.toLowerCase()]) return GIFT_ID_ALIASES[raw.toLowerCase()];

  const exact = TIKTOK_GIFTS.find((g) => g.id === raw || String(g.id) === raw);
  if (exact) return exact.id;

  const fuzzy = TIKTOK_GIFTS.find((g) => {
    const nid = normalizeGiftKey(g.id);
    const nname = normalizeGiftKey(g.name);
    return nid === normalized || nname === normalized || nid.includes(normalized) || normalized.includes(nid);
  });
  return fuzzy?.id || null;
}

export function findGiftDef(incomingIdentifier) {
  const id = resolveGiftId(incomingIdentifier);
  if (!id) return null;
  return TIKTOK_GIFTS.find((g) => g.id === id) || null;
}

/** Migrate saved rule giftIds (crown → little_crown, etc.). */
export function migrateRuleGiftId(giftId) {
  const resolved = resolveGiftId(giftId);
  return resolved || giftId || "rose";
}

export const getGiftById = (incomingIdentifier) => {
  const matched = findGiftDef(incomingIdentifier);
  if (matched) return matched;

  if (incomingIdentifier) {
    console.warn(`⚠️ Unknown Gift Received: "${incomingIdentifier}". Falling back to Rose.`);
  }
  return TIKTOK_GIFTS.find((g) => g.id === "rose") || TIKTOK_GIFTS[0];
};

/** Icons that must stay on disk for default rules + common host picks. */
export function getActiveGiftIconPaths() {
  const ids = new Set(ACTIVE_RULE_GIFT_IDS);
  return TIKTOK_GIFTS.filter((g) => ids.has(g.id)).map((g) => g.icon);
}
